const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
for (const extension of ['.ts', '.tsx']) require.extensions[extension] = (module, filename) => {
  module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: {
    module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020
  } }).outputText, filename)
}
const timeline = require(path.resolve(__dirname, '../src/strategy/timeline.ts'))
const { initialRobots } = require(path.resolve(__dirname, '../src/strategy/fieldGeometry.ts'))
const robots = initialRobots()
const empty = timeline.emptyTimeline()
assert.notEqual(empty.auto.red1, empty.teleop.red1)
assert.equal(timeline.durationForPhase(empty.auto), 15)

let routes = timeline.addWaypoint(empty.auto, robots[0], { x: 28, y: 54 }, 0, 'r1')
routes = timeline.changeWaypoint(routes, 'red1', 'r1', { at: 10, heading: 270 })
routes = timeline.addWaypoint(routes, robots[0], { x: 48, y: 54 }, 10, 'r2')
routes = timeline.changeWaypoint(routes, 'red1', 'r2', { at: 20, heading: 90 })
routes = timeline.addWaypoint(routes, robots[2], { x: 116, y: 50 }, 0, 'b1')
routes = timeline.changeWaypoint(routes, 'blue1', 'b1', { at: 10 })
assert.equal(timeline.durationForPhase(routes), 20)
assert.equal(timeline.robotAtTime(robots[0], routes.red1, 5).x, 18)
assert.equal(timeline.robotAtTime(robots[0], routes.red1, 5).heading, 0, 'heading takes shortest turn from 90 to 270')
assert.equal(timeline.robotAtTime(robots[0], routes.red1, 15).x, 38)
assert.equal(timeline.robotAtTime(robots[0], routes.red1, 30).x, 48)
assert.equal(timeline.robotsAtTime(robots, routes, 5)[2].x, 126, 'all robots move at the same timeline time')
assert.deepEqual(timeline.robotsAtTime(robots, routes, 5), timeline.robotsAtTime(robots, routes, 5), 'playback is deterministic')

const reordered = timeline.reorderWaypoint(routes, 'red1', 'r2', -1)
assert.deepEqual(reordered.red1.map((point) => [point.id, point.at]), [['r2', 10], ['r1', 20]])
const timed = timeline.changeWaypoint(routes, 'red1', 'r1', { at: 25 })
assert(timed.red1[0].at < timed.red1[1].at, 'timing cannot cross the following waypoint')
assert.equal(timeline.removeWaypoint(routes, 'red1', 'r1').red1.length, 1)
const restored = timeline.normalizeTimeline({ auto: routes, teleop: {} })
assert.equal(restored.auto.red1.length, 2)
assert.equal(restored.teleop.red1.length, 0)

const overlapping = timeline.addWaypoint(empty.auto, robots[0], { x: 8, y: 94 }, 0, 'overlap')
assert(timeline.analyzeTimeline(robots, overlapping).some((warning) => warning.kind === 'robot' && warning.robots.includes('red2')))
const outside = timeline.addWaypoint(empty.auto, robots[0], { x: -5, y: 54 }, 0, 'outside')
assert(timeline.analyzeTimeline(robots, outside).some((warning) => warning.kind === 'boundary'))
const frame = timeline.addWaypoint(empty.auto, robots[0], { x: 72, y: 72 }, 0, 'frame')
assert(timeline.analyzeTimeline(robots, frame).some((warning) => warning.kind === 'obstacle'))
assert.equal(timeline.warningsAtTime(robots, empty.auto, 0).length, 0, 'initial positions have no warnings')
console.log('Passed: phase isolation, interpolation, timing, ordering, simultaneous playback, and collision warnings.')
